"""ONNX Runtime drop-in for ModernBertScorer, satisfying run_inference's surface.

run_inference (models/inference.py) touches a model only through:
  model.encoder.config.{cls_token_id, max_position_embeddings}
  next(model.parameters()).device
  model.eval()
  model(input_ids, attention_mask) -> [N] logits

So an ORT session wrapped to expose exactly those four things slots in with no
changes to run_inference or candidate_probabilities. The heavy encoder+head
forward runs in ORT (graph fused once at session load); the softmax/argmax stay
in Python, unchanged.

Inputs are self-generated by run_inference, which already checks CLS-match and
length, so the exported graph (which has no guards) is fed trusted tensors.
"""

import json
from pathlib import Path
from types import SimpleNamespace

import torch


class OnnxScorer:
    """Loads model.onnx + its sidecar json; mimics the ModernBertScorer surface."""

    def __init__(self, onnx_path):
        import onnxruntime as ort  # imported here so torch-only installs still work

        onnx_path = Path(onnx_path)
        meta = json.loads(onnx_path.with_suffix(onnx_path.suffix + ".json").read_text())
        self.tokenizer_id = meta["tokenizer_id"]
        self.encoder = SimpleNamespace(config=SimpleNamespace(
            cls_token_id=meta["cls_token_id"],
            max_position_embeddings=meta["max_position_embeddings"],
        ))
        options = ort.SessionOptions()
        options.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
        self.session = ort.InferenceSession(
            str(onnx_path), options, providers=["CPUExecutionProvider"])
        self._input_names = [i.name for i in self.session.get_inputs()]

    def eval(self):
        return self  # ORT sessions have no train/eval mode

    def parameters(self):
        yield torch.empty(0)  # only used for next(...).device -> cpu

    def __call__(self, input_ids, attention_mask):
        feed = {
            self._input_names[0]: input_ids.cpu().numpy(),
            self._input_names[1]: attention_mask.cpu().numpy(),
        }
        (logits,) = self.session.run(None, feed)
        return torch.from_numpy(logits)
